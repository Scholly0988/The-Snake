const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const storage=new Map();
const context=vm.createContext({window:{localStorage:{getItem:key=>storage.get(key)??null,setItem:(key,value)=>storage.set(key,value)}}});
vm.runInContext(fs.readFileSync('levels.js','utf8'),context);
vm.runInContext(fs.readFileSync('halloween-event.js','utf8'),context);
const run=code=>vm.runInContext(code,context);

assert.equal(run('HalloweenEvent.dialogue.length'),11);
assert.equal(run('HalloweenEvent.dialogue[0].speaker'),'Morgana');
assert.equal(run('HalloweenEvent.dialogue[8].side'),'right');
assert.equal(run('HalloweenEvent.dialogue[8].keepMorgana'),true);
assert.equal(run('HalloweenEvent.segmentHp(1,0)'),44);
assert.equal(run('HalloweenEvent.segmentHp(1,49)'),7800);
assert(run('HalloweenEvent.segmentHp(1,50)')>7800,'grown tail segments continue the HP curve');
for(let level=1;level<=7;level++){
  const hp=JSON.parse(run(`JSON.stringify(Array.from({length:54},(_,i)=>HalloweenEvent.segmentHp(${level},i)))`));
  assert(hp.every((value,index)=>!index||value>hp[index-1]),'event HP must increase at every position');
}
assert.equal(run('HalloweenEvent.pumpkinHp(600)'),300);
assert.equal(run('HalloweenEvent.bonusSegmentHp(800,0,1)'),120);
assert(run('HalloweenEvent.bonusSegmentHp(800,4,1)')>120);
assert.equal(run('HalloweenEvent.backgroundForLevel(1)'),'halloween-event-levels-1-8.webp');
assert.equal(run('HalloweenEvent.backgroundForLevel(8)'),'halloween-event-levels-1-8.webp');
assert.equal(run('HalloweenEvent.backgroundForLevel(9)'),'halloween-event-levels-9-23.webp');
assert.equal(run('HalloweenEvent.backgroundForLevel(23)'),'halloween-event-levels-9-23.webp');
assert.equal(run('HalloweenEvent.backgroundForLevel(24)'),'halloween-event-level-24.webp');
run('HalloweenEvent.save({completed:3,selected:4,introSeen:true})');
const migrated=JSON.parse(run('JSON.stringify(HalloweenEvent.load())'));
assert.equal(migrated.completed,3);assert.equal(migrated.selected,4);assert.equal(migrated.introSeen,true);
assert.equal(migrated.coins,0);assert.equal(migrated.firstClears.length,24);assert.equal(Object.keys(migrated.upgrades).length,10);

assert.equal(run('HalloweenEvent.upgrades.length'),10);
assert.equal(run('HalloweenEvent.upgradeCost(HalloweenEvent.load(),"damage")'),50);
assert.equal(run('HalloweenEvent.upgradeCost(HalloweenEvent.load(),"pierce")'),100);
run('var eventProfile=HalloweenEvent.load();eventProfile.coins=100000;for(let i=0;i<15;i++)HalloweenEvent.buyUpgrade(eventProfile,"pierce")');
assert.equal(run('HalloweenEvent.modifiers(eventProfile).pierce'),3);
assert.equal(run('HalloweenEvent.modifiers(eventProfile).pierceDamage'),6);
assert.equal(run('HalloweenEvent.upgradeCost(eventProfile,"pierce")'),null);
run('eventProfile.upgrades.damage=30;eventProfile.upgrades.rate=30;eventProfile.upgrades.critChance=20;eventProfile.upgrades.critDamage=20;eventProfile.upgrades.pumpkinDamage=20;eventProfile.upgrades.pumpkinHunter=10;eventProfile.upgrades.resistance=20;eventProfile.upgrades.skillHunter=10;eventProfile.upgrades.currency=10');
const mods=JSON.parse(run('JSON.stringify(HalloweenEvent.modifiers(eventProfile))'));
assert.equal(mods.damageMultiplier,1.6);assert.equal(mods.rateMultiplier,1.6);
assert.equal(mods.critChance,10);assert.equal(mods.critDamage,100);
assert.equal(mods.pumpkinDamageMultiplier,2);assert.equal(mods.pumpkinHpMultiplier,.7);
assert.equal(mods.eventDamageMultiplier,1.2);assert.equal(mods.eventSpeedMultiplier,.95);
assert.equal(mods.bonusSpeedMultiplier,.8);assert.equal(mods.skillHpMultiplier,.7);assert.equal(mods.currencyMultiplier,1.5);
assert.equal(run('HalloweenEvent.pumpkinHp(600,eventProfile)'),210);
assert.equal(run('HalloweenEvent.bonusSegmentHp(800,0,1,eventProfile,true)'),84);
let reward=JSON.parse(run('JSON.stringify(HalloweenEvent.rewardForLevel(eventProfile,2))'));
assert.deepEqual(reward,{base:150,firstBonus:300,total:450,first:true,multiplier:1.5});
reward=JSON.parse(run('JSON.stringify(HalloweenEvent.completeLevel(eventProfile,1))'));
assert.equal(reward.total,225);assert.equal(run('eventProfile.coins'),100000-6750+225);
assert.equal(run('HalloweenEvent.rewardForLevel(eventProfile,1).firstBonus'),0);
run('var blockedStorage={getItem(){throw new Error("blocked")},setItem(){throw new Error("blocked")}};var volatileEvent=HalloweenEvent.load(blockedStorage);volatileEvent.coins=321;HalloweenEvent.save(volatileEvent,blockedStorage)');
assert.equal(run('HalloweenEvent.load(blockedStorage).coins'),321,'blocked mobile storage keeps event progress for the active session');
